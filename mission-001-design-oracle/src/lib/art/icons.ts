/** 8×8 pixel icons for the operating panel. */
function icon(rows: string[]): [number, number][] {
  const out: [number, number][] = []
  rows.forEach((row, y) => [...row].forEach((c, x) => c === "#" && out.push([x, y])))
  return out
}

